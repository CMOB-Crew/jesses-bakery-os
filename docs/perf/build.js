// Generates PERFORMANCE-FIXES.md (repo root) and checklist.html (this folder)
// from items.js. Run from anywhere:  node docs/perf/build.js
//
// Ticked checkboxes in the existing PERFORMANCE-FIXES.md are preserved: each
// card carries a hidden <!-- card:id --> marker and its "- [x] Done" state is
// read back before the file is rewritten. Editing a card's words never resets
// its tick.
const fs = require("fs");
const path = require("path");
const { META, GROUPS, ITEMS, GLOSSARY } = require("./items.js");

const REPO = process.argv[2] || path.join(__dirname, "..", "..");
const OUT_HTML = process.argv[3] || path.join(__dirname, "checklist.html");
const MD_PATH = path.join(REPO, META.planFile);

// ---------- carry over existing ticks ----------
const done = new Set();
if (fs.existsSync(MD_PATH)) {
  const old = fs.readFileSync(MD_PATH, "utf8");
  // The checkbox line sits directly under the marker. Only whitespace may
  // separate them, so a tick can never be attributed to the previous card.
  const re = /<!-- card:([a-z0-9-]+) -->\s*- \[(x|X)\] Done/g;
  let m;
  while ((m = re.exec(old))) done.add(m[1]);
}

// ---------- markdown ----------
const gains = { speed: "makes it faster", data: "stops lost work", cost: "costs less to run" };
const L = [];
L.push(`# ${META.title}`);
L.push("");
L.push(`Generated ${META.date} from branch \`${META.branch}\`. This file is the plan an AI coding agent works from. The same cards, in the same order, are on the shared checklist page. The long technical audit is \`${META.auditFile}\`.`);
L.push("");
L.push("> Edit the words in `docs/perf/items.js` and run `node docs/perf/build.js`. Do not edit this file by hand except to tick a card's checkbox; ticks survive regeneration.");
L.push("");
L.push("## Instructions for the agent");
L.push("");
L.push("Read this whole section before touching a file.");
L.push("");
L.push("1. **Follow the rules in `CLAUDE.md`** at the repo root. They exist so the problems below are not reintroduced.");
L.push("2. **Work one card at a time**, top to bottom, starting with the first unchecked card in Phase 1. Do not skip ahead.");
L.push("3. For each card: read every file in **Where** first, make the change described in **Fix**, then run the **Check**. Run `npm run lint` and `npm run build` in `apps/web` before calling a card done.");
L.push("4. **Keep the diff small.** One card, one commit. Name the commit after the card title.");
L.push("5. When the check passes, change the card's `- [ ]` to `- [x]` in this file and stop. Show the person the diff and tell them which card to tick on the checklist page.");
L.push("6. If a check fails or the fix would need something the card does not describe, stop and ask. Do not improvise around it.");
L.push("7. **Never change the database.** No migrations, no schema, no indexes, no moving data. The Parked group lists ideas that would; they are out of scope unless the person says yes in so many words.");
L.push("8. **Phase 4 and Parked are optional. STOP before starting either one and ask:** \"Phases 1 to 3 are done. Phase 4 and Parked are optional and carry more risk. You are the project owner: do you want to continue, and with which cards?\" Do nothing in those groups without a yes for that specific group.");
L.push("9. The **Example** on each card is a made-up snippet that shows the shape of the change. It is not code from the repo. Read the real file and write the real change.");
L.push("10. Do not add `revalidatePath`, `loading.tsx`, Suspense streaming, `cacheComponents`, or prefetching. Those decisions are explained in `CLAUDE.md` and were made from production measurements.");
L.push("11. **Every `unstable_cache` uses the claims-as-argument recipe.** The cached function cannot read cookies, and the database only returns rows for a signed-in user, so the caller passes `await getSessionClaims()` in and the cached function runs `runAsUser(claims, tx => tx\\`...\\`)`. Cast date columns to text in the SQL. Call `revalidateTag(tag, \"max\")` only from route handlers (feed ingest, mail poll), never from a server action.");
L.push("");
L.push("## Progress");
L.push("");
GROUPS.forEach((g) => {
  const all = ITEMS.filter((i) => i.group === g.n);
  const d = all.filter((i) => done.has(i.id)).length;
  L.push(`- ${g.title} — ${g.sub}: ${d} of ${all.length} done${g.optional ? " (optional, ask first)" : ""}`);
});
L.push("");

let idx = 0;
GROUPS.forEach((g) => {
  const all = ITEMS.filter((i) => i.group === g.n);
  L.push("---");
  L.push("");
  L.push(`## ${g.title} — ${g.sub}`);
  L.push("");
  L.push(g.desc);
  L.push("");
  if (g.optional) {
    L.push(`> **STOP AND ASK BEFORE THIS GROUP.** ${g.gate}`);
    L.push(">");
    L.push("> Agent: do not start any card below until the person has answered yes for this group. Ask in one plain sentence and wait.");
    L.push("");
  }
  all.forEach((it) => {
    idx++;
    L.push(`### ${idx}. ${it.title}`);
    L.push("");
    L.push(`<!-- card:${it.id} -->`);
    L.push(`- [${done.has(it.id) ? "x" : " "}] Done`);
    L.push(`- Size: ${it.effort}. Gains: ${it.tags.map((t) => gains[t]).join(", ")}.`);
    L.push("");
    L.push(`**Problem.** ${it.why}`);
    L.push("");
    L.push(`**Fix.** ${it.fix}`);
    L.push("");
    L.push("**Where.**");
    it.where.forEach((w) => L.push(`- \`${w}\``));
    L.push("");
    L.push(`**Check.** ${it.verify}`);
    L.push("");
    L.push("**Example** (shape only, not real code):");
    L.push("");
    L.push("Before:");
    L.push("```");
    L.push(it.ex.before);
    L.push("```");
    L.push("After:");
    L.push("```");
    L.push(it.ex.after);
    L.push("```");
    L.push("");
  });
});
L.push("---");
L.push("");
L.push("## Words used here");
L.push("");
GLOSSARY.forEach(([k, v]) => L.push(`- **${k}.** ${v}`));
L.push("");
fs.writeFileSync(MD_PATH, L.join("\n"));

// ---------- html ----------
const tpl = fs.readFileSync(path.join(__dirname, "template.html"), "utf8");
const data = JSON.stringify({ META, GROUPS, ITEMS, GLOSSARY }).replace(/<\//g, "<\\/");
fs.writeFileSync(OUT_HTML, tpl.replace("__DATA__", data));
console.log(`wrote ${path.relative(REPO, MD_PATH)} (${idx} cards, ${done.size} ticked) and ${path.relative(REPO, OUT_HTML)}`);
